"""Render the actual failed warehouse receipt up to (never into) the LLM client."""
import json
from pathlib import Path
from typing import cast

import pytest
from pydantic import JsonValue

import agent.planner as planner
from agent.machine import AgentState
from agent.mcp_client import MCPTools
from agent.model_selection import MAX_EXPERIMENTAL_PROMPT_MODELS, planning_context
from engine.platform.planning_options import options_digest
from spec.planning import PlanningOptions

FIXTURE = Path(__file__).parent / "fixtures" / "planner-context-warehouse.json"


class BeforeModel(Exception):
    pass


async def capture_prompt(monkeypatch: pytest.MonkeyPatch, *, longer: bool = False,
                         experimental_count: int | None = None) -> dict[str, object]:
    receipt = json.loads(FIXTURE.read_text())
    if experimental_count is not None:
        options = PlanningOptions.model_validate(receipt["tools"]["planning_options"])
        original_ids = {option.capability_id for option in options.experimental_models}
        example = options.experimental_models[0]
        options.experimental_models = [example.model_copy(update={"model_id":f"local-archived-experiment-{index}",
            "capability_id":f"model.local-archived-experiment-{index}"}) for index in range(experimental_count)]
        options.blocked_options = [option for option in options.blocked_options if option.capability_id not in original_ids]
        options.snapshot_id = options_digest(options)
        receipt["tools"]["planning_options"] = options.model_dump(mode="json")
    brief = receipt["brief"]
    if longer:
        brief += "\n" + (
            "The examples show people near shelves and loading equipment. Count only visible people, "
            "including partially visible people whose heads or bodies are distinguishable. Keep the "
            "same object class, whole-image area, confidence and evaluation objective across the two "
            "candidate models. Present bounding boxes and the total visible count on each sample. "
            "Some people are small in the distance, and others stand close together. Treat shadows, "
            "posters and reflections as background unless they clearly show a real person. Preserve "
            "the imported examples and existing human annotations. Show a brief explanation of each "
            "model's recorded training history and the limits of its available evidence. Any boxes "
            "generated by the models are suggestions for review. I will review independent examples "
            "before relying on an accuracy result. Use locally installed compatible choices. If two "
            "suitable default models are unavailable, explain the limitation instead of changing the "
            "task or substituting unrelated classes. Keep the final comparison on the same reviewed "
            "images, and distinguish a successful sample run from a measured quality result."
        )
        assert 1200 <= len(brief) <= 1600

    class CapturedTools:
        operation_id = receipt["operation_id"]
        state = AgentState()

        async def call(self, name: str, arguments: dict[str, JsonValue] | None = None) -> dict[str, JsonValue]:
            assert name in receipt["tools"], "No new tools may execute during captured context replay"
            return cast(dict[str, JsonValue], receipt["tools"][name])

        async def control(self, name: str, arguments: dict[str, JsonValue]) -> dict[str, JsonValue]:
            assert name in {"agent_record_options", "agent_record_skills"}
            return {}

    captured: dict[str, object] = {"brief_characters":len(brief), "model_constructed":False}
    real_check = planner.check_context_size

    def check(system: str, user: str, schema: object) -> None:
        captured.update(system=system, user=user, schema=schema,
            system_characters=len(system), user_characters=len(user), schema_characters=len(json.dumps(schema)),
            total_characters=len(system) + len(user) + len(json.dumps(schema)))
        real_check(system, user, schema)

    def stop(**kwargs: object) -> None:
        raise BeforeModel()

    monkeypatch.setattr(planner, "check_context_size", check)
    monkeypatch.setattr(planner, "AsyncOpenAI", stop)
    try:
        await planner._generate(brief, "media", {"project_id":receipt["project_id"], "use_case":"custom"},
            cast(MCPTools, CapturedTools()), "http://localhost:1234/v1", "never-called")
    except BeforeModel:
        captured["budget_passed"] = True
    except planner.PlannerError as error:
        captured.update(budget_passed=False, error=str(error))
    return captured


@pytest.mark.parametrize("longer", [False, True])
async def test_actual_warehouse_catalog_goal_and_full_render_fit_budget(monkeypatch: pytest.MonkeyPatch, longer: bool) -> None:
    captured = await capture_prompt(monkeypatch, longer=longer)
    assert captured["budget_passed"], captured
    assert captured["total_characters"] <= planner.MAX_INPUT_CHARS  # type: ignore[operator]
    assert captured["model_constructed"] is False
    assert "[skill:alerting" in str(captured["system"]) or "alerting" in str(captured["system"])


async def test_experimental_inventory_growth_has_bounded_prompt_cost(monkeypatch: pytest.MonkeyPatch) -> None:
    captured = await capture_prompt(monkeypatch, longer=True, experimental_count=100)
    assert captured["budget_passed"], captured
    context = json.loads(str(captured["user"]).split("Authoritative engine context:\n", 1)[1])["model_options"]
    assert len(context["experimental_models"]) == MAX_EXPERIMENTAL_PROMPT_MODELS
    assert context["experimental_summary"] == {"total_count":100, "shown_count":8, "omitted_count":92, "purpose_counts":{"unknown":100}}


def test_projection_preserves_full_receipt_and_explicit_eligible_training_facts() -> None:
    options = PlanningOptions.model_validate(json.loads(FIXTURE.read_text())["tools"]["planning_options"])
    before = options.model_dump_json()
    projected = planning_context(options)
    experiments = projected["experimental_models"]
    assert isinstance(experiments, list) and len(experiments) == 6
    assert all(isinstance(item, dict) and set(item) == {"capability_id", "purpose", "reason"} for item in experiments)
    assert options.model_dump_json() == before
    selected = options.experimental_models.pop(0)
    selected.selection_basis = "explicit_experiment"
    options.explicit_model_ids.append(selected.model_id)
    options.eligible_models.append(selected)
    entries = planning_context(options)["eligible_models"]
    assert isinstance(entries, list)
    entry = next(item for item in entries if isinstance(item, dict) and item["capability_id"] == selected.capability_id)
    assert isinstance(entry, dict) and isinstance(entry["training_provenance"], dict)
    assert entry["training_provenance"]["training_samples"] == 10
    assert entry["training_provenance"]["optimizer_steps"] == 50
    assert entry["training_provenance"]["base_model_id"] == "rtdetr-v2-r18"
